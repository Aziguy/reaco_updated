@register.simple_tag
def icon(name: str, css: str = "size-5"):
    return format_html(
        '<svg class="{}" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
        'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
        'aria-hidden="true">{}</svg>',
        css,
        mark_safe(ICONS[name]),  # noqa: S308
    )


def _number(value, places: int) -> str:
    return f"{Decimal(value):,.{places}f}".replace(",", " ").replace(".", ",")


@register.filter
def euro(value):
    if value in (None, ""):
        return "n.c."
    return f"{_number(value, 2)} €"


@register.filter
def co2(value):
    if value in (None, ""):
        return "n.c."
    value = Decimal(value)
    if value < 1:
        return f"{_number(value * 1000, 0)} g CO2e"
    return f"{_number(value, 2)} kg CO2e"


@register.filter
def duration(minutes):
    minutes = int(minutes or 0)
    hours, rest = divmod(minutes, 60)
    if not hours:
        return f"{rest} min"
    return f"{hours} h {rest:02d}" if rest else f"{hours} h"


@register.simple_tag(takes_context=True)
def nav_current(context, prefix: str):
    path = context["request"].path
    current = path == "/" if prefix == "/" else path.startswith(prefix)
    return mark_safe(' aria-current="page"') if current else ""
